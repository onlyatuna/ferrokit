#[test]
fn rounded_rect_region_matches_qt_row_spans() {
    for &(x, y, w, h, r, expected) in ROUNDED {
        let got = Region::from_rounded_rect(Rect::new(x, y, w, h), f64::from(r), f64::from(r));
        assert_same(&format!("rounded ({x},{y},{w},{h}) r={r}"), &got, expected);
    }
}

#[test]
fn ellipse_region_matches_qt_row_spans() {
    for &(x, y, w, h, expected) in ELLIPSES {
        let got = Region::from_rect_type(Rect::new(x, y, w, h), RegionType::Ellipse);
        assert_same(&format!("ellipse ({x},{y},{w},{h})"), &got, expected);
    }
}

#[test]
fn polygon_region_matches_qt_row_spans() {
    for &(name, pts, winding, expected) in POLYGONS {
        let poly = Polygon::from_points(pts.iter().map(|&(x, y)| Point::new(x, y)).collect());
        let rule = if winding {
            FillRule::Winding
        } else {
            FillRule::OddEven
        };
        let got = Region::from_polygon(&poly, rule);
        assert_same(&format!("polygon {name} winding={winding}"), &got, expected);
    }
}

#[test]
fn region_type_rectangle_is_the_rect_and_empty_rects_are_empty() {
    let r = Rect::new(3, 4, 5, 6);
    assert_eq!(
        Region::from_rect_type(r, RegionType::Rectangle),
        Region::from_rect(r)
    );
    assert!(Region::from_rect_type(Rect::new(0, 0, 0, 5), RegionType::Ellipse).is_empty());
    assert!(Region::from_rect_type(Rect::new(0, 0, 5, -1), RegionType::Rectangle).is_empty());
    assert!(Region::from_rounded_rect(Rect::new(0, 0, 0, 5), 3.0, 3.0).is_empty());
}

#[test]
fn polygon_with_fewer_than_three_points_or_huge_height_is_empty() {
    let two = Polygon::from_points(vec![Point::new(0, 0), Point::new(5, 5)]);
    assert!(Region::from_polygon(&two, FillRule::OddEven).is_empty());
    let tall = Polygon::from_points(vec![
        Point::new(0, 0),
        Point::new(10, 200_000),
        Point::new(20, 0),
    ]);
    assert!(Region::from_polygon(&tall, FillRule::Winding).is_empty());
}
