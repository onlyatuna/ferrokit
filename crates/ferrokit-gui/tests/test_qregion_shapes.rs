//! Oracle tests for the curved/polygonal `QRegion` constructors against PySide6 6.11.2.
//!
//! The expected rectangles below were measured from real Qt 6.11.2 (`QT_QPA_PLATFORM=offscreen`,
//! `QRegion.rects()` on Windows) for `QRegion(QPainterPath.addRoundedRect(..).toFillPolygon()
//! .toPolygon())`, `QRegion(QRect, QRegion.Ellipse)` and `QRegion(QPolygon, FillRule)`. Qt's rect
//! decomposition may differ from ours, so both sides are compared as exact per-row pixel spans.
//! The scan converter is software code in Qt, so the oracle is platform independent; the tests are
//! run (and only verified by hand) on Windows, and are not OS-gated.

use ferrokit_gui::geometry::{FillRule, Point, Polygon, Rect, Region, RegionType};
use std::collections::BTreeMap;

type Rects = &'static [(i32, i32, i32, i32)];

/// Merge rects into per-row, sorted, coalesced half-open spans.
fn rows(rects: impl IntoIterator<Item = (i32, i32, i32, i32)>) -> BTreeMap<i32, Vec<(i32, i32)>> {
    let mut map: BTreeMap<i32, Vec<(i32, i32)>> = BTreeMap::new();
    for (x, y, w, h) in rects {
        for row in y..y + h {
            map.entry(row).or_default().push((x, x + w));
        }
    }
    for spans in map.values_mut() {
        spans.sort_unstable();
        let mut merged: Vec<(i32, i32)> = Vec::new();
        for &(a, b) in spans.iter() {
            match merged.last_mut() {
                Some(last) if last.1 == a => last.1 = b,
                _ => merged.push((a, b)),
            }
        }
        *spans = merged;
    }
    map
}

fn region_rows(r: &Region) -> BTreeMap<i32, Vec<(i32, i32)>> {
    rows(r.rects().iter().map(|r| (r.x, r.y, r.width, r.height)))
}

fn assert_same(label: &str, got: &Region, expected: Rects) {
    assert_eq!(region_rows(got), rows(expected.iter().copied()), "{label}");
}

