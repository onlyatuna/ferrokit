fn rgba8(c: Color) -> Rgba {
    let u = c.to_color_u8();
    (u.red(), u.green(), u.blue(), u.alpha())
}

fn color(c: Rgba) -> Color {
    Color::from_rgba8(c.0, c.1, c.2, c.3)
}

#[test]
fn darker_matches_qcolor_bit_for_bit() {
    let bad: Vec<_> = ORACLE
        .iter()
        .filter(|(c, f, d, _)| rgba8(darker(color(*c), *f)) != *d)
        .map(|(c, f, d, _)| (*c, *f, *d, rgba8(darker(color(*c), *f))))
        .collect();
    assert!(bad.is_empty(), "(input, factor, Qt, ours): {bad:?}");
}

#[test]
fn lighter_matches_qcolor_bit_for_bit() {
    let bad: Vec<_> = ORACLE
        .iter()
        .filter(|(c, f, _, l)| rgba8(lighter(color(*c), *f)) != *l)
        .map(|(c, f, _, l)| (*c, *f, *l, rgba8(lighter(color(*c), *f))))
        .collect();
    assert!(bad.is_empty(), "(input, factor, Qt, ours): {bad:?}");
}

#[test]
fn a_non_positive_factor_leaves_the_colour_alone() {
    let c = color((200, 100, 50, 255));
    assert_eq!(rgba8(darker(c, 0)), (200, 100, 50, 255));
    assert_eq!(rgba8(lighter(c, -5)), (200, 100, 50, 255));
}
