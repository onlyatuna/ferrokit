"""Regenerates the golden of tests/test_directwrite_fallbacks.rs: what real Qt on Windows lays out, draws
and reports for the cases the DirectWrite backend decides by the font's own tables, at device pixel
ratios 1 and 1.25.

Needs Windows and PySide6 (measured with 6.12.0). Run it with
`python gen_directwrite_fallbacks_golden.py > directwrite_fallbacks_golden.txt`.

Lines (fields separated by one space; families have `_` for a space):
* `fontset <count> <fnv1a64>`: the number and the hashed sorted names of the font files of the
  machine's font directories; the test compares the lines below only when its machine has the
  same set, since the fallback families of a script are every family that supports it.
* `fb <dpr> <family> <hint> <weight> <px> adv <text id> <1/64 px>` (`QFontMetricsF`
  `horizontalAdvance`) and `fb ... draw <text id> <width> <height> <fnv1a64>` (`QPainter.drawText`
  of the text with a black pen on white into an `ARGB32_Premultiplied` image, ClearType as the
  machine says, hashed as RGBA bytes), for text in scripts the family lacks, so Qt's fallback
  chain of each script item decides the font of each character (`QFontEngineMulti`,
  `fallbacksForFamily`): Hangul, Thai, Han, kana, emoji, arrows and symbols, and for families
  that are missing (the style hint substitute chain) or have no Latin (icon fonts, the space).
"""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FONTS_DIR = os.environ.get("WINDIR", "C:/Windows") + "/Fonts"

TEXTS = {
    "h": "\uc548\ub155\ud558\uc138\uc694 Hello \ud55c\uae00",
    "t": "\u0e2a\u0e27\u0e31\u0e2a\u0e14\u0e35 Hello \u0e20\u0e32\u0e29\u0e32\u0e44\u0e17\u0e22",
    "c": "\u4e2d\u6587\u5b57 \u65e5\u672c\u8a9e Hello",
    "k": "\u3072\u3089\u304c\u306a \u30ab\u30bf\u30ab\u30ca Hello",
    "e": "Hi \U0001F600\U0001F389 ok \u2600 \u2714",
    "a": "a \u2192 b \u2190 c \u21d2 \u2211 \u221e",
    "y": "\u00a9 \u00ae \u2122 \u20ac \u20a9 \u20b9 \u00bd \u2713",
    "r": "Hello \u05e9\u05dc\u05d5\u05dd \u0645\u0631\u062d\u0628\u0627",
    "m": "Abc \u4e2d \ud55c \u0e01 \U0001F600 \u2192 Z",
    "l": "Hamburgefonstiv 0123 AVAWTo",
}
SIZES = (12, 16, 20)
DPRS = (1.0, 1.25)
WEIGHTS = (400, 700)
# (family, hint)
REQUESTS = [(f, "") for f in ("Segoe UI", "Tahoma", "Arial", "Consolas", "Calibri", "Times New Roman", "Courier New", "Microsoft YaHei", "MS Gothic")]
REQUESTS += [("NoSuchFamilyQQQ", h) for h in ("OldEnglish", "Fantasy", "Monospace", "Cursive", "System", "AnyStyle")]
REQUESTS += [(f, "") for f in ("MT Extra", "Bookshelf Symbol 7", "MS Outlook", "Segoe MDL2 Assets", "Segoe Fluent Icons", "SAPGUI-Icons", "Wingdings")]
# Qt's DirectWrite database puts the characters of the Devanagari item after a space or comma into the
# fallback font, which ferrokit does not do yet (measured: 1 to 4 px); the text is left out.


def fnv1a64(data):
    h = 0xCBF29CE484222325
    for b in data:
        h ^= b
        h = (h * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def child(dpr):
    from PySide6.QtCore import QPointF
    from PySide6.QtGui import (QColor, QFont, QFontInfo, QFontMetrics, QFontMetricsF,
                               QGuiApplication, QImage, QPainter)

    app = QGuiApplication(["x", "-platform", "windows"])
    assert abs(app.devicePixelRatio() - dpr) < 1e-9, (app.devicePixelRatio(), dpr)

    def draw_hash(font, px, text):
        w, h = 360, (px * 2 + 15) // 4 * 4  # a multiple of 4: whole pixels at ratio 1.25
        img = QImage(round(w * dpr), round(h * dpr), QImage.Format_ARGB32_Premultiplied)
        img.setDevicePixelRatio(dpr)
        img.fill(QColor(255, 255, 255, 255))
        p = QPainter(img)
        p.setPen(QColor(0, 0, 0, 255))
        p.setFont(font)
        p.drawText(QPointF(6.0, px + 6.0), text)
        p.end()
        raw = bytes(img.constBits())
        bpl = img.bytesPerLine()
        out = bytearray()
        for y in range(img.height()):
            row = raw[y * bpl:y * bpl + img.width() * 4]
            for x in range(img.width()):
                b, g, r, a = row[x * 4:x * 4 + 4]
                out += bytes((r, g, b, a))
        return img.width(), img.height(), "%016x" % fnv1a64(out)

    def font_of(family, px, weight, italic):
        font = QFont(family)
        font.setPixelSize(px)
        font.setWeight(QFont.Weight(weight))
        font.setItalic(italic)
        return font

    def fixed(value):
        v = value * 64
        assert v == int(v), value
        return int(v)

    if dpr == 1.0:
        print("# Generated by gen_directwrite_fallbacks_golden.py from PySide6 %s (Qt %s), platform "
              "windows" % (__import__("PySide6").__version__,
                           __import__("PySide6.QtCore").QtCore.qVersion()))

    def header(file):
        path = os.path.join(FONTS_DIR, file)
        if not os.path.exists(path):
            sys.stderr.write("skipping %s: not installed\n" % file)
            return False
        with open(path, "rb") as f:
            data = f.read()
        print("sysfont", file, len(data), "%016x" % fnv1a64(data))
        return True

    names = []
    for root in (FONTS_DIR, os.path.join(os.environ.get("LOCALAPPDATA", ""), "Microsoft/Windows/Fonts")):
        if os.path.isdir(root):
            names += sorted(os.listdir(root))
    print("fontset", len(names), "%016x" % fnv1a64("\n".join(names).encode("utf-8")))
    hints = {"": None, "AnyStyle": QFont.AnyStyle, "OldEnglish": QFont.OldEnglish, "Fantasy": QFont.Fantasy,
             "Monospace": QFont.Monospace, "Cursive": QFont.Cursive, "System": QFont.System}
    for family, hint in REQUESTS:
        for weight in WEIGHTS:
            for px in SIZES:
                font = QFont(family)
                font.setPixelSize(px)
                font.setWeight(QFont.Weight(weight))
                if hints[hint] is not None:
                    font.setStyleHint(hints[hint])
                head = "fb %s %s %s %d %d" % (repr(dpr), family.replace(" ", "_"), hint or "-", weight, px)
                mf = QFontMetricsF(font)
                for text_id, text in TEXTS.items():
                    print(head, "adv", text_id, fixed(mf.horizontalAdvance(text)))
                for text_id in ("h", "c", "k"):
                    w, h, hs = draw_hash(font, px, TEXTS[text_id])
                    print(head, "draw", text_id, w, h, hs)


def screen_dpr():
    env = dict(os.environ)
    env.pop("QT_SCALE_FACTOR", None)
    env.pop("QT_ENABLE_HIGHDPI_SCALING", None)
    return float(subprocess.run(
        [sys.executable, "-c",
         "from PySide6.QtGui import QGuiApplication; import sys; "
         "a = QGuiApplication(sys.argv[:1]); print(a.devicePixelRatio())"],
        capture_output=True, text=True, env=env, check=True).stdout)


def main():
    base = screen_dpr()
    chunks = []
    for dpr in DPRS:
        env = dict(os.environ)
        env.pop("QT_SCALE_FACTOR", None)
        env.pop("QT_ENABLE_HIGHDPI_SCALING", None)
        if dpr == 1.0:
            env["QT_ENABLE_HIGHDPI_SCALING"] = "0"
        elif abs(dpr - base) > 1e-9:
            env["QT_SCALE_FACTOR"] = repr(dpr / base)
        out = subprocess.run([sys.executable, __file__, "child", repr(dpr)], capture_output=True,
                             text=True, env=env, encoding="utf-8")
        sys.stderr.write(out.stderr)
        if out.returncode:
            raise SystemExit("child failed")
        chunks.append(out.stdout)
    # Every child prints its own `sysfont` headers; the test applies the header above a line.
    sys.stdout.reconfigure(encoding="utf-8", newline="\n")
    for chunk in chunks:
        sys.stdout.write(chunk)


if __name__ == "__main__":
    if len(sys.argv) > 2 and sys.argv[1] == "child":
        sys.stdout.reconfigure(encoding="utf-8", newline="\n")
        child(float(sys.argv[2]))
    else:
        main()
